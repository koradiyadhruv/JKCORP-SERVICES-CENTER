(function () {
  const savedLang = localStorage.getItem('jkcorp_lang') || 'gu';
  const savedTheme = localStorage.getItem('jkcorp_theme') || 'ocean';

  function applyTheme(theme) {
    document.body.dataset.theme = theme;
    document.querySelectorAll('.theme-btn').forEach((button) => {
      button.classList.toggle('active', button.dataset.theme === theme);
    });
    localStorage.setItem('jkcorp_theme', theme);
  }

  function applyLanguage(lang) {
    const dict = translations[lang] || translations.gu;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const key = element.dataset.i18n;
      if (dict[key]) {
        element.textContent = dict[key];
      }
    });
    document.querySelectorAll('.lang-btn').forEach((button) => {
      button.classList.toggle('active', button.dataset.lang === lang);
    });
    localStorage.setItem('jkcorp_lang', lang);
  }

  document.querySelectorAll('.theme-btn').forEach((button) => {
    button.addEventListener('click', () => applyTheme(button.dataset.theme));
  });

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => applyLanguage(button.dataset.lang));
  });

  const nav = document.getElementById('mainnav');
  const hamburger = document.getElementById('hamburger');
  hamburger?.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('open');
    hamburger.setAttribute('aria-expanded', String(isOpen));
  });
  nav?.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => nav.classList.remove('open'));
  });

  document.querySelectorAll('.faq-question').forEach((button) => {
    button.addEventListener('click', () => {
      const item = button.closest('.faq-item');
      const open = item.classList.toggle('open');
      button.setAttribute('aria-expanded', String(open));
    });
  });

  const form = document.getElementById('contact-form');
  const formStatus = document.getElementById('form-status');
  form?.addEventListener('submit', (event) => {
    event.preventDefault();
    const formData = new FormData(form);
    const name = String(formData.get('name') || '').trim();
    const phone = String(formData.get('phone') || '').trim();
    const service = String(formData.get('service') || '').trim();
    const message = String(formData.get('message') || '').trim();
    const dict = translations[document.documentElement.lang] || translations.gu;

    if (!/^[0-9+\-\s]{7,15}$/.test(phone)) {
      formStatus.textContent = dict.invalidPhone || 'Please enter a valid phone number.';
      formStatus.className = 'form-status error';
      document.getElementById('phone').focus();
      return;
    }

    const mailBody = [
      `Name: ${name}`,
      `Phone: ${phone}`,
      `Service: ${service}`,
      `Message: ${message || 'No message provided'}`,
      '',
      'Submitted from JKCORP website.'
    ].join('\n');

    formStatus.textContent = dict.sending || 'Sending...';
    formStatus.className = 'form-status';

    const previewLink = `mailto:jkcorpofficial@gmail.com?subject=${encodeURIComponent('New service inquiry')}&body=${encodeURIComponent(mailBody)}`;
    form.reset();
    window.location.href = previewLink;
    formStatus.textContent = dict.formSuccess || 'Your inquiry was sent successfully.';
    formStatus.className = 'form-status success';
  });

  const backToTop = document.getElementById('backToTop');
  window.addEventListener('scroll', () => {
    if (backToTop) {
      backToTop.classList.toggle('show', window.scrollY > 200);
    }
  }, { passive: true });
  backToTop?.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));

  const cookieConsent = document.getElementById('cookie-consent');
  const acceptButton = document.getElementById('accept-cookies');
  const rejectButton = document.getElementById('reject-cookies');
  if (localStorage.getItem('jkcorp_cookie') === 'yes' || localStorage.getItem('jkcorp_cookie') === 'no') {
    cookieConsent.style.display = 'none';
  }
  acceptButton?.addEventListener('click', () => {
    localStorage.setItem('jkcorp_cookie', 'yes');
    cookieConsent.style.display = 'none';
  });
  rejectButton?.addEventListener('click', () => {
    localStorage.setItem('jkcorp_cookie', 'no');
    cookieConsent.style.display = 'none';
  });

  applyTheme(savedTheme);
  applyLanguage(savedLang);

  if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => {
      navigator.serviceWorker.register('/sw.js').catch(() => {});
    });
  }
})();
